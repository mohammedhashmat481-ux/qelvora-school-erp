/**
 * Generate AI Topic Summary (Grounded in Shared Study Material Library)
 */
export async function generateTopicSummary({
  standard = '10th',
  board = 'CBSE',
  subject = 'Science',
  topic = '',
  style = 'Standard Notes',
  teacherInstructions = '',
  selectedResourceIds = [],
  userId = null,
  schoolId = null
}) {
  if (!topic || !topic.trim()) {
    throw new Error('Topic name is required for summary generation.');
  }

  const cleanTopic = topic.trim();

  // 1. RAG Retrieval from Shared Study Material Library
  let matchingResources = [];
  const validResourceIds = Array.isArray(selectedResourceIds)
    ? selectedResourceIds.filter(id => typeof id === 'string' && id.trim().length > 0)
    : [];

  if (validResourceIds.length > 0) {
    matchingResources = await prisma.questionPaperResource.findMany({
      where: { id: { in: validResourceIds } }
    });
  } else {
    // Automatic lookup matching standard, subject and board
    matchingResources = await prisma.questionPaperResource.findMany({
      where: {
        board,
        standard,
        subject
      },
      take: 10
    });
  }

  const ragResult = retrieveRelevantChunks({
    resources: matchingResources,
    selectedChapters: [cleanTopic],
    maxChunksPerSubject: 8
  });

  // 2. Formulate AI Prompt based on Style & Instructions
  const styleGuidelines = {
    'Quick Revision': 'Format as high-impact revision bullet points, concise definitions, formula cheatsheet, and memory flashcards.',
    'Standard Notes': 'Format as comprehensive, classroom-ready study notes with structured headings, definitions, step-by-step explanations, and real-world examples.',
    'Detailed Notes': 'Format as an in-depth textbook chapter breakdown with deep conceptual exploration, complete derivations, edge cases, and comparison tables.',
    'Exam-Oriented Notes': 'Format specifically for board examination success, highlighting expected questions, step-by-step marking schemes, examiner tips, and common traps.'
  };

  const selectedGuideline = styleGuidelines[style] || styleGuidelines['Standard Notes'];

  const prompt = `You are an expert curriculum educator for school students (${standard}, Board: ${board}).
Generate high-quality, student-friendly academic study notes for the topic: "${cleanTopic}" in Subject: "${subject}".

Style: ${style} (${selectedGuideline})

${ragResult.contextText ? `GROUNDED SOURCE CONTEXT FROM TEXTBOOK / SYLLABUS:\n${ragResult.contextText}\n` : 'Use accurate standard school curriculum concepts.'}

${teacherInstructions ? `TEACHER INSTRUCTIONS (MANDATORY TO FOLLOW):\n${teacherInstructions}\n` : ''}

REQUIRED STRUCTURE:
1. Topic Overview & Core Definition
2. Key Principles & Step-by-Step Detailed Explanations
3. Mathematical Equations, Formulas & Worked Examples (with SI units where applicable)
4. Real-World Applications & Daily Life Examples
5. Important Examination Points & Common Student Mistakes to Avoid
6. Quick Revision Flashpoints
7. Practice Questions (Short & Long Answer questions)

Return clean, beautiful GitHub-flavored markdown with bold concepts, numbered steps, and LaTeX math formulas ($...$ or $$...$$).`;

  let summaryText = '';
  let provider = 'gemini';
  let model = process.env.GEMINI_MODEL || 'gemini-1.5-flash';

  try {
    summaryText = await callGemini(prompt, 'You are an award-winning academic educator writing clear, student-friendly study notes.');
  } catch (aiErr) {
    console.warn(`⚠️ [Summary AI] Gemini API call failed: ${redactSecrets(aiErr.message)}. Serving development fallback summary.`);
    provider = 'mock';
    model = 'dev-fallback-engine';
    summaryText = generateDevelopmentSummary({
      standard,
      board,
      subject,
      topic: cleanTopic,
      style,
      teacherInstructions,
      sourcesSummary: ragResult.sourcesSummary
    });
  }

  // 3. Sanitize for WIN-1252 safety before saving to database
  const safeTitle = sanitizeForDb(`${cleanTopic} - ${style} (${standard} ${subject})`);
  const safeSummary = sanitizeForDb(summaryText);
  const safeInstructions = sanitizeForDb(teacherInstructions);

  let savedRecord = null;
  try {
    savedRecord = await prisma.topicSummary.create({
      data: {
        userId: userId || null,
        schoolId: schoolId || null,
        standard,
        board,
        subject,
        topic: cleanTopic,
        style,
        title: safeTitle,
        summary: safeSummary,
        teacherInstructions: safeInstructions,
        sourcesUsed: ragResult.sourcesSummary || [],
        provider,
        model
      }
    });
  } catch (dbErr) {
    console.warn('⚠️ Warning: Failed to save topic summary to database:', dbErr.message);
  }

  return {
    success: true,
    id: savedRecord?.id || `SUM-${Date.now()}`,
    title: safeTitle,
    summary: safeSummary,
    standard,
    board,
    subject,
    topic: cleanTopic,
    style,
    sourcesUsed: ragResult.sourcesSummary || [],
    provider,
    model,
    createdAt: savedRecord?.createdAt || new Date().toISOString()
  };
}
